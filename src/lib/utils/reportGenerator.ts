import type { Deadline, DocumentAnalysis } from '@/lib/ai/types';

/** Google Calendar template link (no OAuth needed) */
export function googleCalendarTemplateUrl(
  deadline: Deadline,
  documentTitle: string
): string | null {
  if (!deadline.date) return null;
  const clean = deadline.date.replace(/[^0-9-]/g, '');
  const parts = clean.split('-');
  if (parts.length < 3) return null;
  const compact = `${parts[0]}${parts[1].padStart(2, '0')}${parts[2].padStart(2, '0')}`;
  const text = encodeURIComponent(`Sahay Deadline: ${deadline.description} (${documentTitle})`);
  const details = encodeURIComponent(
    `Document: ${documentTitle}\nReference: ${deadline.original_text}\nVerify on official portal before due date.`
  );
  return `https://calendar.google.com/calendar/render?action=TEMPLATE&text=${text}&dates=${compact}/${compact}&details=${details}`;
}

