/**
 * Build a clean printable citizen report (HTML string).
 * Used for Print / Save-as-PDF via a print window.
 */
export function buildCitizenReportHtml(analysis: DocumentAnalysis): string {
  const esc = (s: string) =>
    (s || '')
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
  const steps = analysis.action_steps
    .map((s, i) => `<li><strong>${i + 1}. ${esc(s.title)}</strong><br/>${esc(s.description)}</li>`)
    .join('');
  const deadlines = analysis.deadlines
    .map((d) => `<li><strong>${esc(d.description)}</strong> — ${esc(d.date || d.original_text)} <em>(${esc(d.original_text)})</em></li>`)
    .join('');
  const facts = analysis.key_facts
    .map((f) => `<tr><td>${esc(f.label)}</td><td><strong>${esc(f.value)}</strong></td></tr>`)
    .join('');
  const sources = analysis.sources
    .map((s) => `<li>${esc(s.title)} (${esc(s.publisher)}) — ${esc(s.url)}<br/><em>${esc(s.supports)}</em></li>`)
    .join('');

  return `<!doctype html><html><head><meta charset="utf-8"/>
<title>Sahay Citizen Report — ${esc(analysis.document_type.label)}</title>
<style>
body{font-family:Georgia,serif;color:#111;padding:32px;max-width:800px;margin:0 auto;line-height:1.55}
h1{font-size:22px;color:#0F4C3A}h2{font-size:16px;color:#0F4C3A;margin-top:24px;border-bottom:1px solid #ddd;padding-bottom:4px}
table{border-collapse:collapse;width:100%}td{border:1px solid #ccc;padding:6px 10px;font-size:13px}
li{margin-bottom:6px;font-size:13.5px}.meta{color:#555;font-size:12px}
@media print{.no-print{display:none}}
</style></head><body>
<p class="meta">Sahay AI Citizen Report • Generated ${new Date().toLocaleString('en-IN')} • Not a legal certificate — verify with issuing office.</p>
<h1>${esc(analysis.document_type.label)}</h1>
<p><strong>Summary:</strong> ${esc(analysis.summary)}</p>
${analysis.why_received ? `<p><strong>Why received:</strong> ${esc(analysis.why_received)}</p>` : ''}
${analysis.what_it_means ? `<p><strong>What it means:</strong> ${esc(analysis.what_it_means)}</p>` : ''}
<h2>Key Facts</h2><table>${facts}</table>
<h2>Action Checklist</h2><ol>${steps}</ol>
<h2>Deadlines</h2><ul>${deadlines}</ul>
<h2>Official Sources</h2><ul>${sources}</ul>
${analysis.uncertainties?.length ? `<h2>Needs Verification</h2><ul>${analysis.uncertainties.map((u) => `<li>${esc(u)}</li>`).join('')}</ul>` : ''}
<p class="meta">File: ${esc(analysis.fileName || '')} • Shared via Sahay AI Citizen Assistant</p>
<div class="no-print" style="margin-top:16px"><button onclick="window.print()">Print / Save PDF</button></div>
<script>window.onload=function(){setTimeout(function(){window.print()},400)}</script>
</body></html>`;
}

export function downloadCitizenReport(analysis: DocumentAnalysis) {
  const html = buildCitizenReportHtml(analysis);
  const w = window.open('', '_blank');
  if (!w) return;
  w.document.write(html);
  w.document.close();
}

export function downloadMarkdownBrief(analysis: DocumentAnalysis) {
  const lines = [
    `# ${analysis.document_type.label}`,
    '',
    `> ${analysis.summary}`,
    '',
    '## Action steps',
    ...analysis.action_steps.map((s, i) => `${i + 1}. **${s.title}** — ${s.description}`),
    '',
    '## Deadlines',
    ...analysis.deadlines.map((d) => `- **${d.description}**: ${d.date || d.original_text} (${d.original_text})`),
    '',
    '## Official sources',
    ...analysis.sources.map((s) => `- [${s.title}](${s.url}) — ${s.publisher}`),
    '',
    '_Generated by Sahay AI Citizen Assistant_',
  ];
  const blob = new Blob([lines.join('\n')], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `Sahay_Brief_${Date.now()}.md`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
